-- ── 2. H5: the group school year and the placement year check ───────────
-- The read-only Production dry run of 2026-10-29 found 8 groups, each with a valid
-- year, and no live enrollment of another year or without a year (plan record).

-- A group year against an enrollment year, both normalised by school_year_of
-- (2026-2027 = 2026/2027). D-H5b = A: a group without a valid year refuses.
create function academic_security.check_group_year(p_annee text, p_year text, p_errcode text default '23514')
returns void language plpgsql stable set search_path = pg_catalog, pg_temp as $$
declare v_group text := academic_security.school_year_of(p_annee);
begin
  if v_group is null then
    raise exception 'Renseignez l’année scolaire du groupe.' using errcode = p_errcode, hint = 'egc.group_year_missing';
  end if;
  if academic_security.school_year_of(p_year) is distinct from v_group then
    raise exception 'L’année scolaire de l’inscription (%) ne correspond pas à celle du groupe (%).',
      coalesce(p_year, 'non renseignée'), v_group using errcode = p_errcode, hint = 'egc.school_year_mismatch';
  end if;
end $$;

-- D-H5c = A: every path that places an enrollment in a group, for every role. Only a
-- new group or a new year is checked; status changes, ends and the year close are not.
-- The group row is share-locked, so a concurrent change of its year waits or is seen.
create function academic_security.guard_enrollment_group_year() returns trigger
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
declare v_annee text;
begin
  if new.group_id is null then return new; end if;
  -- Only the consumed Batch D clean-up revert (egc_revert_cleanup) sets both flags:
  -- it restores journalled before-images verbatim.
  if current_setting('eh.membership_sync', true) = 'on' and current_setting('eh.enrollment_command', true) = 'on' then
    return new;
  end if;
  if tg_op = 'UPDATE' and new.group_id is not distinct from old.group_id
     and new.school_year is not distinct from old.school_year then
    return new;
  end if;
  select g.annee into v_annee from public.groups g where g.id = new.group_id for share;
  if not found then return new; end if;
  -- An enrollment placed without a year takes its group's.
  if new.school_year is null then new.school_year := academic_security.school_year_of(v_annee); end if;
  perform academic_security.check_group_year(v_annee, new.school_year);
  return new;
end $$;
create trigger enrollment_group_year_guard before insert or update of group_id, school_year on public.enrollments
  for each row execute function academic_security.guard_enrollment_group_year();

-- D-H5a = A: a new group without a year takes the school year of today's centre date
-- (also when a command passes an explicit NULL). D-H5b = A: a group year is a school
-- year, and it cannot change while a live enrollment of another year is in the group
-- (as programme and level, D7).
create function academic_security.guard_group_year() returns trigger
language plpgsql security definer set search_path = pg_catalog, pg_temp as $$
begin
  if tg_op = 'INSERT' and nullif(btrim(new.annee), '') is null then
    new.annee := replace(public.centre_school_year(), '/', '-');
  end if;
  if tg_op = 'UPDATE' and new.annee is not distinct from old.annee then return new; end if;
  if nullif(btrim(new.annee), '') is not null and academic_security.school_year_of(new.annee) is null then
    raise exception 'Année scolaire du groupe invalide : utilisez le format 2026-2027.'
      using errcode = '22023', hint = 'egc.group_year_invalid';
  end if;
  if tg_op = 'UPDATE' and exists (select 1 from public.enrollments e where e.group_id = old.id
      and e.status in ('Submitted','Under Review','Confirmed','Validated','Trial')
      and academic_security.school_year_of(e.school_year) is distinct from academic_security.school_year_of(new.annee)) then
    raise exception 'Réaffectez les apprenants avant de changer l’année scolaire du groupe.'
      using errcode = '23514', hint = 'egc.group_year_locked';
  end if;
  return new;
end $$;
create trigger groups_year_guard before insert or update of annee on public.groups
  for each row execute function academic_security.guard_group_year();

revoke all on function academic_security.check_group_year(text, text, text) from public, anon, authenticated, service_role;
revoke all on function academic_security.guard_enrollment_group_year() from public, anon, authenticated, service_role;
revoke all on function academic_security.guard_group_year() from public, anon, authenticated, service_role;

