-- D-TZ-2, D-H5a, D-H5b and D-H5c all A). Forward-only and transactional; it changes
-- no row, no grant on an existing object and no policy.
--
-- 1. H7, one centre clock: public.centre_utc_offset() (UTC+0) replaces the zone name
--    'Africa/Casablanca' (and the CRM policy timezone column, which may only hold
--    that name) in every time computation; public.business_date() follows it.
-- 2. H5: a new group without a year takes the current school year; a group year is
--    locked while learners of another year are in it; every placement checks the
--    enrollment year against the group's (2026-2027 = 2026/2027).
-- 3. Re-created functions, generated by scripts/generate-centre-clock.py from the
--    124 catalog: 28 with only the H7 substitution, create_charge_payment_financial
--    without the 10 % reception discount cap (H1), crm_start_enrollment,
--    save_receptionist_enrollment and crm_enrollment_groups with the H5 year.
--    Kept on purpose: the Meta ad account's own time zone (crm_get_marketing_cohort)
--    and the consumed Batch D clean-up academic_security.egc_cleanup_c1.
-- The restore is scripts/rollback/125_audit_follow_ups_restore.sql (not run without
-- its own approval).
begin;

