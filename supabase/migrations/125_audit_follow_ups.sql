-- ── 1. H7: the centre clock ──────────────────────────────────────────────
-- The centre's clock: Morocco, UTC+0 since 2026-09-20 (tzdata 2026c). This is the
-- one place to change it in the database; it mirrors CENTRE_UTC_OFFSET_MINUTES in
-- src/lib/centreClock.mjs. No zone name is read, so stale time-zone data on any
-- server cannot move it. In AT TIME ZONE an interval uses the ISO sign (east
-- positive); a text offset such as '+01:00' would be read with the POSIX sign.
-- STABLE, not IMMUTABLE: no index or generated column may depend on the value.
create function public.centre_utc_offset() returns interval
language sql stable set search_path = pg_catalog, pg_temp
as $$ select interval '0 hours' $$;

-- The business date of an instant: receipt year, payment window, reports, today.
create or replace function public.business_date(p_at timestamptz default now()) returns date
language sql stable set search_path = pg_catalog, pg_temp
as $$ select (p_at at time zone public.centre_utc_offset())::date $$;

-- School year of a centre date, 'YYYY/YYYY' (1 September to 31 August).
create function public.centre_school_year(p_date date default public.business_date()) returns text
language sql stable set search_path = pg_catalog, pg_temp
as $$ select y::text || '/' || (y + 1)::text
  from (select extract(year from p_date)::integer - case when extract(month from p_date) < 9 then 1 else 0 end as y) x $$;

-- Same callers as business_date.
